/** 낱말로 그림을 찾는다. 빈 낱말이면 전부. */
export function searchStickers(word, list = STICKERS) {
  const q = String(word ?? '').replace(/\s+/g, ' ').trim();
  if (!q) return list;
  const parts = q.split(' ');
  return list.filter((s) => parts.every((p) => s.k.includes(p) || s.e === p));
}
